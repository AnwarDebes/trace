"""Generate paper/_numbers.tex (every numeric result macro) from results/*.json.

This makes the paper's numbers a deterministic function of the experiment
outputs. Run after experiments/run_all.py, before compiling the paper.  Also
prints a markdown results table for the README.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = ROOT / "paper" / "_numbers.tex"


def load(name):
    p = RES / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def f3(x):
    return f"{x:.3f}"


def fmt_p(p):
    if p < 1e-4:
        return r"{<}10^{-4}"
    if p < 1e-3:
        return r"{<}10^{-3}"
    return f"{p:.3f}"


NAME = {"linsvc": "LinearSVC", "logreg": "LogReg", "majority": "Majority"}


def main():
    macros = {}

    cg = load("content_guard")
    if cg:
        pi = cg["datasets"]["prompt_injection"]
        s = pi["summary"]["trace"]
        macros["piTrace"] = f3(s["f1"]["mean"]); macros["piTraceSd"] = f3(s["f1"]["std"])
        macros["piLat"] = str(int(round(s["latency_us"]["mean"])))
        macros["piSize"] = f"{s['model_bytes']['mean']/1024:.1f}"
        bb = pi["best_baseline"]
        macros["piBest"] = f3(pi["summary"][bb]["f1"]["mean"]); macros["piBestName"] = NAME.get(bb, bb)
        macros["piP"] = fmt_p(pi["trace_vs_best_baseline_f1"]["p_value"])
        jb = cg["datasets"]["jailbreak"]
        js = jb["summary"]["trace"]
        macros["jbTrace"] = f3(js["f1"]["mean"]); macros["jbTraceSd"] = f3(js["f1"]["std"])
        macros["jbLat"] = str(int(round(js["latency_us"]["mean"])))
        jbb = jb["best_baseline"]
        macros["jbBest"] = f3(jb["summary"][jbb]["f1"]["mean"]); macros["jbBestName"] = NAME.get(jbb, jbb)

    bt = load("behavior_trajectory")
    if bt:
        cap = {"exfiltration": "Exf", "missing_audit": "Aud",
               "privilege": "Pri", "scope": "Sco"}
        for fam, C in cap.items():
            fa = bt["families"][fam]["summary"]
            macros[f"bt{C}PcA"] = f3(fa["per_call"]["asr"]["mean"])
            macros[f"bt{C}PcF"] = f3(fa["per_call"]["fpr"]["mean"])
            macros[f"bt{C}TrA"] = f3(fa["trace"]["asr"]["mean"])
            macros[f"bt{C}TrF"] = f3(fa["trace"]["fpr"]["mean"])

    ab = load("ablation")
    if ab:
        o = ab["overall_attack_recall"]
        macros["ablContent"] = f3(o["content_only"]["mean"])
        macros["ablBehavior"] = f3(o["behavior_only"]["mean"])
        macros["ablTrace"] = f3(o["trace"]["mean"])

    tm = load("tamper_evidence")
    if tm:
        rates = [v["detection_rate"] for v in tm["tampers"].values()] + [tm["forged_signature_detection_rate"]]
        macros["tamperRate"] = f"{min(rates):.2f}"
        macros["verifyUs"] = str(int(round(tm["verify_latency_us"]["mean"])))

    sb = load("systems_benchmark")
    if sb:
        macros["behLat"] = f"{sb['behavior']['latency']['median_us']:.2f}"
        macros["behMem"] = str(int(sb["behavior"]["monitor_memory_bytes"]))
        led = sb.get("ledger_scaling")
        if led:
            macros["ledgerBytes"] = str(int(round(sum(r["bytes_per_entry"] for r in led) / len(led))))
        # deployed C=200 content-guard latency (median / p99)
        c200 = next((r for r in sb["content_sweep"] if r["n_clauses"] == 200), None)
        if c200:
            macros["latMed"] = str(int(round(c200["latency"]["median_us"])))
            macros["latPNN"] = str(int(round(c200["latency"]["p99_us"])))
    if cg:
        macros["latStd"] = str(int(round(
            cg["datasets"]["prompt_injection"]["summary"]["trace"]["latency_us"]["std"])))

    ar = load("adaptive_robustness")
    if ar:
        macros["obfPlain"] = f3(ar["obfuscation"]["plain_recall"]["mean"])
        macros["obfSpace"] = f3(ar["obfuscation"]["space_out_recall"]["mean"])
        tr = ar["transfer"]
        a = tr["prompt_injection__to__jailbreak"]
        b = tr["jailbreak__to__prompt_injection"]
        macros["transAin"] = f3(a["in_domain_f1"]); macros["transAcross"] = f3(a["cross_domain_f1"])
        macros["transBin"] = f3(b["in_domain_f1"]); macros["transBcross"] = f3(b["cross_domain_f1"])

    lines = ["% AUTO-GENERATED by scripts/paper_numbers.py. Do not edit by hand."]
    for k, v in macros.items():
        lines.append(f"\\renewcommand{{\\{k}}}{{{v}}}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(macros)} macros)")
    for k, v in macros.items():
        print(f"  {k} = {v}")


if __name__ == "__main__":
    main()
